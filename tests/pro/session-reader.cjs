"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const os = require("node:os");
const crypto = require("node:crypto");
const { SessionReader } = require("../../src/pro/session-reader.cjs");
const { SessionJournal } = require("../../src/pro/session-journal.cjs");
const { SessionLog } = require("../../src/pro/session-log.cjs");
test("read-only session query scopes owner and preserves results after shell loss", t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "relay-session-reader-")); t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const sessionId = crypto.randomUUID(), owner = crypto.randomUUID(), deviceId = crypto.randomUUID(), requestId = crypto.randomUUID();
  const dir = path.join(root, sessionId), options = { dir, sessionId, owner, deviceId, platform: "linux", osBoot: "boot" };
  const journal = new SessionJournal(options);
  fs.writeFileSync(path.join(dir, "session.json"), JSON.stringify(options));
  journal.accept(owner, { requestId, sequence: 1, spec: { command: "private" } }); journal.claim(owner, requestId);
  const log = new SessionLog(journal.directory(requestId)); log.append("stdout", Buffer.from("中文")); log.finish();
  journal.complete(owner, requestId, { exitCode: 0 });
  const before = fs.readFileSync(journal.manifest, "utf8"); let authorized = true;
  const reader = new SessionReader({ dir: root, deviceId, authorized: id => authorized, osBoot: "boot", runnerLive: () => false });
  const result = reader.get(owner, { sessionId, requestId, limitBytes: 2 });
  assert.equal(result.completed, true); assert.equal(result.sessionState, "unknown");
  assert.equal(result.stdout.nextOffset, 2); assert.equal(JSON.stringify(result).includes("private"), false);
  assert.equal(fs.readFileSync(journal.manifest, "utf8"), before);
  assert.throws(() => reader.get(crypto.randomUUID(), { sessionId, requestId }), { code: "SESSION_NOT_FOUND" });
  authorized = false;
  assert.throws(() => reader.get(owner, { sessionId, requestId }), { code: "AUTH_REVOKED" });
  authorized = true;
  const rebooted = new SessionReader({ dir: root, deviceId, authorized: () => true, osBoot: "new-boot" });
  assert.equal(rebooted.get(owner, { sessionId, requestId }).sessionState, "lost");
  assert.equal(rebooted.get(owner, { sessionId, requestId }).result.exitCode, 0);
});
